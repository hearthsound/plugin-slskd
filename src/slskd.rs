//! Serde types for the slskd API.
//!
//! The shapes follow slskd 0.26's controllers: camelCase JSON, enums as
//! strings, and `null` members omitted. Request bodies carry every field the
//! plugin sets, because slskd's documented defaults are not the defaults its
//! search actually uses; responses are deserialized with defaults throughout,
//! so a member slskd adds or omits between releases does not break a call.
//!
//! Everything here is pure: it never touches the network, so it is unit-tested
//! on the host target against captured response fixtures.

/// Body of `POST /api/v0/searches`.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SearchRequest {
    /// Id of the search, generated by the plugin so it can poll the search
    /// immediately and correlate responses with it.
    pub id: String,
    /// The text every matching file path must contain.
    pub search_text: String,
    /// How long the search may run, in **milliseconds**.
    ///
    /// slskd documents this member as seconds but forwards it to Soulseek.NET,
    /// which reads it as milliseconds, so the value is passed through as the
    /// plugin's configuration names it.
    pub search_timeout: u32,
    /// Maximum number of peer responses slskd keeps.
    pub response_limit: u32,
    /// Maximum number of files slskd keeps.
    pub file_limit: u32,
    /// Whether slskd drops responses whose files do not look like the request.
    pub filter_responses: bool,
    /// Peers slower than this are dropped, in bytes per second.
    pub minimum_peer_upload_speed: u32,
    /// Responses from peers with a longer upload queue are dropped.
    pub maximum_peer_queue_length: u32,
}

/// A search, as `GET /api/v0/searches/{id}` reports it.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Search {
    /// Id of the search.
    pub id: String,
    /// Whether the search has ended.
    ///
    /// slskd keeps a search's responses in memory until it ends, so the
    /// responses are only readable once this flag is set.
    #[serde(default)]
    pub is_complete: bool,
    /// State flags of the search, comma-joined, for example `Completed, TimedOut`.
    #[serde(default)]
    pub state: String,
    /// Number of responses the search has collected.
    #[serde(default)]
    pub response_count: u64,
    /// Number of files the search has collected.
    #[serde(default)]
    pub file_count: u64,
}

/// One peer response, as `GET /api/v0/searches/{id}/responses` reports it.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SearchResponse {
    /// Name of the peer that answered.
    #[serde(default)]
    pub username: String,
    /// Files the peer offers.
    #[serde(default)]
    pub files: Vec<File>,
    /// Number of files the peer keeps locked.
    #[serde(default)]
    pub locked_file_count: u64,
    /// Length of the peer's upload queue.
    #[serde(default)]
    pub queue_length: u64,
    /// Whether the peer has a free upload slot.
    #[serde(default)]
    pub has_free_upload_slot: bool,
    /// The peer's reported upload speed, in bytes per second.
    #[serde(default)]
    pub upload_speed: u64,
}

/// One file of a peer response.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct File {
    /// Remote path exactly as the peer sent it, with backslashes.
    pub filename: String,
    /// File size in bytes.
    #[serde(default)]
    pub size: u64,
    /// File extension, without the dot.
    #[serde(default)]
    pub extension: String,
    /// Bitrate in kilobits per second, when the peer reported one.
    #[serde(default)]
    pub bit_rate: Option<u32>,
    /// Sample rate in hertz, when the peer reported one.
    #[serde(default)]
    pub sample_rate: Option<u32>,
    /// Bit depth, when the peer reported one.
    #[serde(default)]
    pub bit_depth: Option<u32>,
    /// Length in seconds, when the peer reported one.
    #[serde(default)]
    pub length: Option<u32>,
    /// Whether the file is locked, which means the peer does not share it.
    #[serde(default)]
    pub is_locked: bool,
}

/// Body of `POST /api/v0/transfers/downloads/batches`.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct EnqueueBatchRequest {
    /// Id of the batch, generated by the plugin so it can read the batch back
    /// without waiting for a response.
    pub id: String,
    /// Name of the peer that offers the files.
    pub username: String,
    /// Files to download.
    pub files: Vec<BatchFile>,
    /// Where slskd puts the downloaded files.
    pub options: BatchOptions,
}

/// One file of a batch request.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BatchFile {
    /// Remote path, exactly as the peer reported it.
    pub filename: String,
    /// Size in bytes.
    pub size: u64,
}

/// Where a batch's files are downloaded to.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BatchOptions {
    /// Destination directory, relative to slskd's downloads directory.
    ///
    /// slskd uses this verbatim, without expanding its own destination tokens.
    /// Whether it flattens every file of the batch to its file name under it or
    /// keeps the remote subfolders is not settled, so the plugin checks both
    /// layouts ([`crate::download`]).
    pub destination: String,
}

/// Response of `POST /api/v0/transfers/downloads/batches`.
///
/// Only the failures matter: the plugin names the batch itself, so a successful
/// response has nothing to tell it.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct EnqueueBatchResponse {
    /// Files slskd refused to enqueue.
    #[serde(default)]
    pub failures: Vec<Failure>,
}

/// One file slskd refused to enqueue.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Failure {
    /// Remote path of the file.
    #[serde(default)]
    pub filename: String,
    /// Why slskd refused it.
    #[serde(default)]
    pub message: String,
}

/// A transfer batch, as `GET /api/v0/transfers/downloads/batches/{id}` reports
/// it.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Batch {
    /// Id of the batch.
    #[serde(default)]
    pub id: String,
    /// Name of the peer the files come from.
    #[serde(default)]
    pub username: String,
    /// Transfers of the batch, one per file.
    #[serde(default)]
    pub transfers: Vec<Transfer>,
}

/// One transfer of a batch.
#[derive(Debug, Clone, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Transfer {
    /// Id of the transfer, which is also the id slskd's transfer routes use.
    #[serde(default)]
    pub id: String,
    /// Remote path of the file, as it was enqueued.
    #[serde(default)]
    pub filename: String,
    /// Size in bytes.
    #[serde(default)]
    pub size: u64,
    /// State flags, comma-joined, for example `Completed, Succeeded`.
    #[serde(default)]
    pub state: String,
    /// Bytes transferred so far.
    #[serde(default)]
    pub bytes_transferred: u64,
    /// Average transfer speed so far, in bytes per second.
    #[serde(default)]
    pub average_speed: f64,
    /// Position in the peer's upload queue, when slskd knows it.
    #[serde(default)]
    pub place_in_queue: Option<u32>,
    /// The exception slskd recorded for a failed transfer.
    #[serde(default)]
    pub exception: String,
}

/// Returns the file name part of a remote path.
///
/// Remote paths arrive exactly as the peer sent them, with backslashes, and a
/// peer may mix separators, so both are treated as separators.
///
/// # Parameters
///
/// - `path`: the remote path.
///
/// # Returns
///
/// Everything after the last separator, or the whole path when it has none.
///
/// # Example
///
/// ```text
/// basename("@@tqkz\\Music\\01 Song.flac") -> "01 Song.flac"
/// ```
pub fn basename(path: &str) -> &str {
    path.rsplit(['\\', '/']).next().unwrap_or(path)
}

/// Returns a remote file's name without its extension.
///
/// # Parameters
///
/// - `path`: the remote path.
///
/// # Returns
///
/// The file name up to its last dot. A name that starts with the dot, or has
/// no dot at all, is returned whole.
///
/// # Example
///
/// ```text
/// stem("@@tqkz\\Music\\01 Song.flac") -> "01 Song"
/// stem("@@tqkz\\Music\\archive.tar.gz") -> "archive.tar"
/// ```
pub fn stem(path: &str) -> &str {
    let name = basename(path);
    match name.rsplit_once('.') {
        Some((stem, extension)) if !stem.is_empty() && !extension.is_empty() => stem,
        _ => name,
    }
}

/// Returns the extension of a remote path.
///
/// # Parameters
///
/// - `path`: the remote path.
///
/// # Returns
///
/// The text after the last dot of the file name, lower-cased and without the
/// dot, and the empty string when the name has no usable extension.
///
/// # Example
///
/// ```text
/// extension("@@tqkz\\Music\\01 Song.FLAC") -> "flac"
/// extension("@@tqkz\\Music\\no-extension") -> ""
/// ```
pub fn extension(path: &str) -> String {
    let name = basename(path);
    match name.rsplit_once('.') {
        Some((stem, extension)) if !stem.is_empty() && !extension.is_empty() => {
            extension.to_lowercase()
        }
        _ => String::new(),
    }
}

/// Returns the directory part of a remote path.
///
/// # Parameters
///
/// - `path`: the remote path.
///
/// # Returns
///
/// Everything before the last separator, and the empty string when the path has
/// none.
///
/// # Example
///
/// ```text
/// directory("@@tqkz\\Music\\01 Song.flac") -> "@@tqkz\\Music"
/// directory("01 Song.flac") -> ""
/// ```
pub fn directory(path: &str) -> &str {
    match path.rfind(['\\', '/']) {
        Some(index) => &path[..index],
        None => "",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn takes_the_file_name_of_a_remote_path() {
        assert_eq!(basename("@@tqkz\\Music\\01 Song.flac"), "01 Song.flac");
        assert_eq!(basename("C:/Music/01 Song.flac"), "01 Song.flac");
        assert_eq!(basename("01 Song.flac"), "01 Song.flac");
        assert_eq!(basename(""), "");
    }

    #[test]
    fn takes_the_directory_of_a_remote_path() {
        assert_eq!(
            directory("@@tqkz\\Music\\Album\\01 Song.flac"),
            "@@tqkz\\Music\\Album"
        );
        assert_eq!(directory("C:/Music/01 Song.flac"), "C:/Music");
        assert_eq!(directory("01 Song.flac"), "");
        assert_eq!(directory(""), "");
    }

    #[test]
    fn removes_only_the_last_extension() {
        assert_eq!(stem("@@tqkz\\Music\\01 Song.flac"), "01 Song");
        assert_eq!(stem("@@tqkz\\Music\\archive.tar.gz"), "archive.tar");
        assert_eq!(stem("@@tqkz\\Music\\no-extension"), "no-extension");
        assert_eq!(stem("@@tqkz\\Music\\Music\\.hidden"), ".hidden");
    }

    #[test]
    fn lower_cases_the_extension() {
        assert_eq!(extension("@@tqkz\\Music\\01 Song.FLAC"), "flac");
        assert_eq!(extension("@@tqkz\\Music\\archive.tar.gz"), "gz");
        assert_eq!(extension("@@tqkz\\Music\\no-extension"), "");
        assert_eq!(extension("@@tqkz\\Music\\.hidden"), "");
    }

    #[test]
    fn serializes_a_batch_request_the_way_slskd_reads_it() {
        let request = EnqueueBatchRequest {
            id: "4c1f0b7a-4e2d-4c5f-8a6b-0d1e2f3a4b5c".to_string(),
            username: "peer_free".to_string(),
            files: vec![BatchFile {
                filename: "@@tqkz\\Music\\01 Windowlicker.flac".to_string(),
                size: 48_410_233,
            }],
            options: BatchOptions {
                destination: "hearthsound/0f8b".to_string(),
            },
        };

        let json = serde_json::to_value(&request).unwrap();

        assert_eq!(json["username"], "peer_free");
        assert_eq!(json["options"]["destination"], "hearthsound/0f8b");
        assert_eq!(json["files"][0]["size"], 48_410_233);
        assert_eq!(
            json["files"][0]["filename"],
            "@@tqkz\\Music\\01 Windowlicker.flac"
        );
    }

    #[test]
    fn reads_an_enqueued_batch_response() {
        let response: EnqueueBatchResponse =
            serde_json::from_str(include_str!("fixtures/batch_enqueued.json")).unwrap();

        assert!(response.failures.is_empty());
    }

    #[test]
    fn reads_a_partial_batch_response() {
        let response: EnqueueBatchResponse =
            serde_json::from_str(include_str!("fixtures/batch_partial.json")).unwrap();

        assert_eq!(response.failures.len(), 1);
        assert_eq!(response.failures[0].filename, "@@abcd\\music\\one.mp3");
        assert!(response.failures[0].message.contains("queue"));
    }

    #[test]
    fn reads_a_batch_with_its_transfers() {
        let batch: Batch =
            serde_json::from_str(include_str!("fixtures/batch_downloading.json")).unwrap();

        assert_eq!(batch.id, "4c1f0b7a-4e2d-4c5f-8a6b-0d1e2f3a4b5c");
        assert_eq!(batch.username, "peer_free");
        assert_eq!(batch.transfers.len(), 1);

        let transfer = &batch.transfers[0];
        assert_eq!(transfer.filename, "@@tqkz\\Music\\01 Windowlicker.flac");
        assert_eq!(transfer.state, "InProgress");
        assert_eq!(transfer.bytes_transferred, 12_000_000);
        assert_eq!(transfer.average_speed, 640_000.5);
        assert_eq!(transfer.place_in_queue, None);
    }

    #[test]
    fn serializes_a_search_request_the_way_slskd_reads_it() {
        let request = SearchRequest {
            id: "8f14e45f-ceea-467f-a1c8-9c5b0d1b4f3a".to_string(),
            search_text: "Aphex Twin Windowlicker".to_string(),
            search_timeout: 15_000,
            response_limit: 100,
            file_limit: 10_000,
            filter_responses: true,
            minimum_peer_upload_speed: 0,
            maximum_peer_queue_length: 50,
        };

        let json = serde_json::to_value(&request).unwrap();

        assert_eq!(json["searchTimeout"], 15_000);
        assert_eq!(json["filterResponses"], true);
        assert_eq!(json["minimumPeerUploadSpeed"], 0);
        assert_eq!(json["maximumPeerQueueLength"], 50);
        assert_eq!(json["fileLimit"], 10_000);
        assert_eq!(json["responseLimit"], 100);
        assert_eq!(json["searchText"], "Aphex Twin Windowlicker");
        assert!(json.get("searchTimeoutMs").is_none());
    }

    #[test]
    fn reads_a_running_search() {
        let search: Search =
            serde_json::from_str(include_str!("fixtures/search_running.json")).unwrap();

        assert_eq!(search.id, "8f14e45f-ceea-467f-a1c8-9c5b0d1b4f3a");
        assert!(!search.is_complete);
        assert_eq!(search.state, "InProgress");
        assert_eq!(search.response_count, 0);
    }

    #[test]
    fn reads_a_completed_search() {
        let search: Search =
            serde_json::from_str(include_str!("fixtures/search_complete.json")).unwrap();

        assert!(search.is_complete);
        assert_eq!(search.state, "Completed");
        assert_eq!(search.response_count, 3);
        assert_eq!(search.file_count, 5);
    }

    #[test]
    fn reads_a_response_list() {
        let responses: Vec<SearchResponse> =
            serde_json::from_str(include_str!("fixtures/search_responses.json")).unwrap();

        assert_eq!(responses.len(), 3);
        assert_eq!(responses[0].username, "peer_free");
        assert_eq!(responses[0].files.len(), 2);
        assert_eq!(responses[0].queue_length, 0);
        assert!(responses[0].has_free_upload_slot);
        assert_eq!(responses[0].upload_speed, 812_345);
        assert_eq!(responses[0].files[0].extension, "flac");
        assert_eq!(responses[0].files[0].bit_depth, Some(16));
        assert_eq!(responses[0].files[0].length, Some(366));
        assert!(responses[0].files[1].is_locked);
        assert_eq!(responses[1].files[0].bit_depth, None);
    }
}
